"""Assemble the published artifact: the product's source, its own git history, and a README.

The artifact is not a build output. It is a **codebase a developer can clone and run**: every
tracked file of the product's main branch, a fresh `git init` history containing exactly that
tree, and a README that documents how to install, build, run and test it.

Two consequences are deliberate.

First, `git init` runs inside the artifact directory rather than copying the product
repository's `.git`. Copying the product's history would drag along the operator's branch
layout, stale worktree pointers and every abandoned experiment; a fresh single commit is what
a hand-off should look like, and it cannot carry a remote URL or credential from the factory.

Second, build output (`release/`, `.nuxt/`, `node_modules/`) is excluded. It is regenerated by
`npm ci && npm run build` from the locked manifest, it is large, and it is machine-specific.
Shipping it would make the artifact hundreds of megabytes and silently stale.
"""
from pathlib import Path

from . import products

# Files a build tool recreates; never shipped, even if a product forgets to ignore them.
# `zig-out` and `.zig-cache` are the Zig equivalents of `dist` and `node_modules`: both are
# regenerated by `zig build`, and `zig-out/bin/app` is ~9 MB of Debug binary that a hand-off
# must not carry. Leaving them out shipped a compiled binary inside a source artifact.
EXCLUDED_DIRS = {"node_modules", "release", ".nuxt", ".output", ".data", ".git", "dist", "build",
                 "zig-out", ".zig-cache"}
# The product's ignore rules are respected, but these are matched without one.
EXCLUDED_NAMES = {".env", ".env.local", ".env.production", ".DS_Store"}

README_NAME = "README.md"


def tracked_output_files(root: Path) -> list[str]:
    """Every file under ``root`` that belongs in a hand-off.

    Walks the filesystem rather than asking git for `ls-files`: the caller hands over an
    *export* of the product branch (see `products.export_tree`), which is a plain directory
    with no `.git`. Asking git there failed every build. Working from the filesystem also
    means the exclusion list is what decides, rather than whatever a product chose to track.
    """
    kept = []
    for path in sorted(root.rglob("*")):
        if path.is_symlink() or not path.is_file():
            continue
        name = path.relative_to(root).as_posix()
        parts = Path(name).parts
        if any(part in EXCLUDED_DIRS for part in parts):
            continue
        if Path(name).name in EXCLUDED_NAMES:
            continue
        if Path(name).name == README_NAME:
            # Regenerated below so it always describes this artifact rather than the
            # factory's own README, which a product may have copied in.
            continue
        kept.append(name)
    return kept


def render_readme(project: dict, profile, plan, artifact: dict) -> str:
    """A README derived from the approved plan and the profile that built it.

    Deliberately template-driven rather than model-written: a README that hallucinates an
    install step is worse than no README, and the values below are facts the factory already
    knows. Anything the factory cannot know is left as an explicit placeholder.
    """
    commands = profile.commands or []
    steps = "\n".join(f"{index}. `{' '.join(argv)}`" for index, argv in enumerate(commands, 1)) or \
        "_(no build commands were configured for this project)_"
    serve = " ".join(profile.serve_argv) if profile.serve_argv else ""
    tester = (
        f"The factory that produced this project ran API and browser acceptance cases against "
        f"`{profile.readiness_path}` after the build. Run your own equivalent before shipping a "
        f"change.\n"
        if profile.tester else ""
    )
    env_note = (
        "This project expects these environment variables. They are supplied by the environment, "
        "never committed:\n\n"
        + "\n".join(f"- `{name}`" for name in sorted(profile.env))
        + "\n\nA database file is created inside the data directory at runtime; do not commit it.\n\n"
        if profile.env else ""
    )
    tasks = "\n".join(f"- **{task.id}** — {task.title}" for task in plan.tasks) if plan else ""

    return f"""# {project['name']}

{plan.summary if plan else ''}

Generated by Anton Software Factory. The git history in this repository starts at the commit
that recorded this hand-off; it is not the factory's own history.

## Requirements

- Node.js 24 or newer
- npm

## Install and build

```sh
npm ci
```

The approved build sequence for this project was:

{steps}

## Run

{("```sh\n" + serve + "\n```") if serve else "_(no run command was configured for this project)_"}

{env_note}## Verify

{tester}
## What this project was asked to do

{tasks}

## Notes

- `package-lock.json` is included so `npm ci` reproduces the dependency tree exactly.
- Build output (`node_modules/`, the build directory) is not included; regenerate it with the
  commands above.
"""


def assemble(project: dict, profile, plan, source_root: Path, destination: Path,
             commit_message: str) -> dict:
    """Materialise the artifact directory: tracked source + generated README + fresh git."""
    import shutil

    if destination.exists():
        shutil.rmtree(destination)
    destination.mkdir(parents=True)

    copied = []
    for name in tracked_output_files(source_root):
        target = destination / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source_root / name, target)
        if (source_root / name).stat().st_mode & 0o111:
            target.chmod(0o755)
        copied.append(name)

    readme = render_readme(project, profile, plan, {})
    (destination / README_NAME).write_text(readme)
    copied.append(README_NAME)

    # A fresh history, so the hand-off carries no factory branches or remote configuration.
    products.init_artifact_repo(destination, commit_message)
    return {"files": len(copied), "git": True}
