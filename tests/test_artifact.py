"""The published artifact is a runnable codebase, not a build output.

It must contain the product's source, a README explaining how to run it, and its own single
-commit git history -- and it must not contain build output, which is regenerated by the
commands the README documents.
"""
import json
import subprocess
from pathlib import Path


from factory import artifact as artifact_module
from factory.models import Plan, Profile
from factory.workspace import extract, package

ROOT = Path(__file__).resolve().parent.parent

PLAN = Plan.model_validate({
    "summary": "A small site with an editable hero and an API health endpoint.",
    "tasks": [
        {"id": "scaffold", "title": "Scaffold the app",
         "instructions": "Create the project scaffold.", "acceptance": ["builds"]},
        {"id": "home", "title": "Build the home page",
         "instructions": "Render the hero.", "acceptance": ["renders"], "depends_on": ["scaffold"]},
    ],
    "test_flows": [],
})


def studio_profile():
    data = json.loads((ROOT / "examples" / "config-studio-linux.json").read_text())
    return Profile.model_validate(data["profiles"]["nuxt-studio"])


def make_source(tmp_path, extra=None):
    source = tmp_path / "source"
    (source / "pages").mkdir(parents=True)
    (source / "pages" / "index.vue").write_text("<template><h1>hi</h1></template>\n")
    (source / "package.json").write_text('{"name":"demo"}\n')
    (source / "package-lock.json").write_text('{"lockfileVersion":3}\n')
    (source / ".gitignore").write_text("node_modules/\nrelease/\n")
    # Build output must never be published, even if it is present.
    (source / "release" / "server").mkdir(parents=True)
    (source / "release" / "server" / "index.mjs").write_text("// built\n")
    (source / "node_modules" / "pkg").mkdir(parents=True)
    (source / "node_modules" / "pkg" / "index.js").write_text("// dep\n")
    for name, text in (extra or {}).items():
        (source / name).write_text(text)
    return source


def test_artifact_contains_source_readme_and_its_own_git(tmp_path):
    source = make_source(tmp_path)
    destination = tmp_path / "published"
    meta = artifact_module.assemble({"name": "Demo"}, studio_profile(), PLAN, source,
                                    destination, "verified build, revision 1")

    assert meta["git"] is True
    assert (destination / ".git").is_dir(), "the hand-off must carry its own history"
    readme = (destination / "README.md").read_text()
    assert "# Demo" in readme
    assert "npm ci" in readme, "the README must document how to install"
    assert "npm run build" in readme

    # Build output is excluded; the lockfile is kept so `npm ci` is reproducible.
    assert not (destination / "release").exists()
    assert not (destination / "node_modules").exists()
    assert (destination / "package-lock.json").is_file()
    assert (destination / "pages" / "index.vue").is_file()

    log = subprocess.run(["git", "log", "--oneline"], cwd=destination,
                         capture_output=True, text=True).stdout.strip()
    assert len(log.splitlines()) == 1, "a hand-off starts from a single commit"
    status = subprocess.run(["git", "status", "--porcelain"], cwd=destination,
                            capture_output=True, text=True).stdout
    assert status == "", f"the artifact repository must be clean, got {status!r}"


def test_artifact_git_has_no_remote_from_the_factory(tmp_path):
    """A copied .git would leak the operator's branches and remote configuration."""
    source = make_source(tmp_path)
    destination = tmp_path / "published"
    artifact_module.assemble({"name": "Demo"}, studio_profile(), PLAN, source,
                             destination, "hand-off")
    remotes = subprocess.run(["git", "remote", "-v"], cwd=destination,
                             capture_output=True, text=True).stdout
    assert remotes == ""
    branches = subprocess.run(["git", "branch", "--list"], cwd=destination,
                              capture_output=True, text=True).stdout
    assert branches.strip().endswith("main")


def test_product_readme_is_replaced_not_shipped_verbatim(tmp_path):
    """A product may contain a README; the hand-off must describe how to run *this* build."""
    source = make_source(tmp_path, {"README.md": "# factory documentation\n"})
    destination = tmp_path / "published"
    artifact_module.assemble({"name": "Demo"}, studio_profile(), PLAN, source,
                             destination, "hand-off")
    readme = (destination / "README.md").read_text()
    assert "factory documentation" not in readme
    assert "# Demo" in readme


def test_artifact_round_trips_through_package_and_extract(tmp_path):
    source = make_source(tmp_path)
    destination = tmp_path / "published"
    artifact_module.assemble({"name": "Demo"}, studio_profile(), PLAN, source,
                             destination, "hand-off")
    tarball = tmp_path / "artifact.tar.gz"
    record = package(destination, tarball)

    restored = tmp_path / "restored"
    extract(tarball.read_bytes(), restored)

    assert (restored / ".git").is_dir()
    assert (restored / "README.md").is_file()
    log = subprocess.run(["git", "log", "--oneline"], cwd=restored,
                         capture_output=True, text=True).stdout.strip()
    assert log, "the restored artifact must remain a working repository"
    # The compressed artifact is far smaller than the build-output artifacts it replaced.
    assert record["bytes"] < 5_000_000


def test_readme_names_the_environment_the_app_expects():
    readme = artifact_module.render_readme({"name": "Demo"}, studio_profile(), PLAN, {})
    assert "DATABASE_URL" in readme and "DATA_DIR" in readme
    assert "do not commit" in readme.lower()
